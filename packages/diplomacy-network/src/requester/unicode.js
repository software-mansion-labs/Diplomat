// Unicode 17.0.0 as Go 1.27's regular expressions read it: the general category and the
// script of every code point (unicode.Categories, unicode.Scripts) and the code points each
// folds to (unicode.SimpleFold), written out from Go's tables at the end of this file.

/// The code points `\p{name}` stands for in a Go regular expression, as `{ table, fold }`:
/// `table` sorted [lo, hi] pairs, `fold` whether `(?i)` adds what they fold to, which Go
/// does only for some names. Null for a name Go does not know. A name is looked up as Go
/// looks it up: "_", "-" and " " dropped, the first letter upper case and the rest lower.
export function unicodeClass(name) {
  const key = canonical(name);
  let found = classes.get(key);
  if (found === undefined) {
    const table = tableOf(key);
    if (table === null) return null;
    classes.set(key, (found = { table, fold: FOLDED.has(key) }));
  }
  return found;
}

/// Whether `table`, sorted [lo, hi] pairs, holds `c`, found by halving the table.
export function holds(table, c) {
  let lo = 0;
  let hi = table.length >> 1;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (table[2 * mid + 1] < c) lo = mid + 1;
    else hi = mid;
  }
  return 2 * lo < table.length && table[2 * lo] <= c;
}

/// The other code points of the orbit unicode.SimpleFold takes `c` around, which Go's
/// `(?i)` matches for it: none for most.
export function foldsOf(c) {
  return orbits().get(c) ?? NONE;
}

/// `pairs`, [lo, hi] pairs in any order, as a sorted table with no two pairs touching.
export function tableFrom(pairs) {
  const sorted = [...pairs].sort((a, b) => a[0] - b[0]);
  const out = [];
  for (const [lo, hi] of sorted) {
    if (out.length > 0 && lo <= out.at(-1) + 1) out[out.length - 1] = Math.max(out.at(-1), hi);
    else out.push(lo, hi);
  }
  return Int32Array.from(out);
}

const canonical = (name) => {
  let out = '';
  for (const c of name) {
    if (c === '_' || c === '-' || c === ' ') continue;
    out += out === '' ? (c >= 'a' && c <= 'z' ? c.toUpperCase() : c) : (c >= 'A' && c <= 'Z' ? c.toLowerCase() : c);
  }
  return out;
};

