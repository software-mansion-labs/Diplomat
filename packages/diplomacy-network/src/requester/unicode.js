// The names whose class (?i) folds: those of unicode.FoldCategory and unicode.FoldScript,
// their long names, and ASCII, which Go folds by a table of its own. Any and Assigned fold
// to themselves.
const FOLDING = ['L', 'Ll', 'Lt', 'Lu', 'M', 'Mn'];
const FOLDED = new Set([...FOLDING, ...[...ALIASES].filter(([, is]) => FOLDING.includes(is)).map(([name]) => name), 'Common', 'Greek', 'Inherited', 'Ascii']);
const classes = new Map();
const NONE = Object.freeze([]);

// The table of the name `key`, canonical, or null for none.
function tableOf(key) {
  if (key === 'Any') return Int32Array.of(0, 0x10ffff);
  if (key === 'Ascii') return Int32Array.of(0, 0x7f);
  if (key === 'Assigned') {
    // All but Cn, which starts after U+0000 and ends at U+10FFFF.
    const unassigned = tableOf('Cn');
    return Int32Array.from([0, ...unassigned.subarray(0, -1)], (c, k) => (k === 0 ? 0 : k % 2 === 1 ? c - 1 : c + 1));
  }
  const category = ALIASES.get(key) ?? key;
  const leaves = (GROUPS[category] ?? category).split(' ');
  if (leaves.every((leaf) => CATEGORIES.includes(leaf))) return collect(CATEGORY_RUNS, leaves.map((leaf) => CATEGORIES.indexOf(leaf)));
  const script = SCRIPTS.findIndex((s) => canonical(s) === key);
  return script < 0 ? null : collect(SCRIPT_RUNS, [script]);
}

// The code points whose owner in `runs` (lengths in base 36, each followed by its owner's
// index in base 26 written with A-Z) is one of `owners`, as a table.
function collect(runs, owners) {
  const out = [];
  let at = 0;
  for (const [, length, owner] of runs.matchAll(/([0-9a-z]+)([A-Z]+)/g)) {
    const next = at + parseInt(length, 36);
    if (owners.includes([...owner].reduce((n, d) => n * 26 + d.charCodeAt(0) - 65, 0))) {
      if (out.length > 0 && out.at(-1) === at - 1) out[out.length - 1] = next - 1;
      else out.push(at, next - 1);
    }
    at = next;
  }
  return Int32Array.from(out);
}

let folds = null;
// Each code point that folds to another, to the others of its orbit.
function orbits() {
  if (folds !== null) return folds;
  folds = new Map();
  let first = 0;
  for (const group of ORBITS.split(' ')) {
    const steps = group.split(',').map((d) => parseInt(d, 36));
    first += steps[0];
    const orbit = [first];
    for (const step of steps.slice(1)) orbit.push(orbit.at(-1) + step);
    for (const c of orbit) folds.set(c, Object.freeze(orbit.filter((other) => other !== c)));
  }
  return folds;
}

